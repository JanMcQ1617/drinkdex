/* The proof board (../index.html) draws the type from the five shipped */
/* cuts in assets/fonts/ and the ground from assets/details/ground.png, */
/* so the only marks it cannot take from a file are the ones the app    */
/* draws from code at run time: the drink page's outlined "Nº 0147" at  */
/* cap 48 (numeralPath, Anton's own outlines since v4.10, with the º    */
/* drawn as Anton's degree ring) and the caught plate's drip            */
/* (penPath). Both are imported from src/ itself, as render-details     */
/* does, so the board draws what ships and not a copy of it. The pen    */
/* marks that do not change in v4.10 come from the v4.9 board's         */
/* generated marks.js, read in place.                                   */
/*                                                                      */
/* Writes ../figures.js (GENERATED).                                    */
/* Run (repo root):  node specs/v4.10/board-final/tools/build.mjs       */
/* ==================================================================== */
import { writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { fileURLToPath } from 'node:url';

/* The app's modules import extensionless ('./penPath'); retry a failed relative import with ".ts", as render-details does. */
registerHooks({
  resolve(spec, ctx, next) {
    try {
      return next(spec, ctx);
    } catch (e) {
      if (spec.startsWith('.') && !/\.[cm]?[jt]sx?$/.test(spec)) return next(`${spec}.ts`, ctx);
      throw e;
    }
  },
});
process.removeAllListeners('warning');

const { numeral } = await import('../../../../src/components/details/numeralPath.ts');
const { plateDrip, PEN } = await import('../../../../src/components/details/penPath.ts');

const pick = (s) => ({ d: s.d, box: s.box });
const out = {
  /* The drink page's lead (DrinkPanels HowLead): the plate's spelling, at NUMERAL_CAP 48. */
  'Nº 0147': { ...pick(numeral('Nº 0147', 48)), width: numeral('Nº 0147', 48).width, cap: 48 },
  /* PlateDrip: its frame's origin PEN.drip.inset - 1 in from the plate's right, PEN.drip.overlap - 1 up from its foot. */
  drip: { ...pick(plateDrip()), inset: PEN.drip.inset, overlap: PEN.drip.overlap },
};
const file = fileURLToPath(new URL('../figures.js', import.meta.url));
writeFileSync(file, `/* GENERATED by tools/build.mjs from src/components/details. Do not edit. */\nwindow.FIGURES=${JSON.stringify(out)};\n`);
console.log(`  wrote ${file}`);
