import React from 'react';
import { type StyleProp, useWindowDimensions, View, type ViewStyle } from 'react-native';
import Svg, { Path } from 'react-native-svg';

import { colors } from '@/constants/theme';

import { WORDMARK_BASELINE, WORDMARK_PATH, WORDMARK_SM_PATH, WORDMARK_X_TOP } from './paths';

/* ==================================================================== */
/* The wordmark: "sipply", tagged in red paint pen                      */
/*                                                                      */
/* v4.5 "Marker tag" (Jan, 20 Oct 2026; specs/v4.5-logo/scribble). A    */
/* hand-drawn lowercase script with a small drip off the y's swash. It  */
/* replaced the Playfair "Sipply" everywhere the app set its name, so   */
/* Playfair is now drink names only (check-design rule 6). The letters  */
/* are outlined paths, no font: brand/paths.ts holds them, generated by */
/* scripts/build-icons.mjs from scripts/icon/wordmark*.svg, the same    */
/* files the brand rasters come from.                                   */
/*                                                                      */
/* CAMPARI. The logo is the accent's sixth place (theme.ts; check-      */
/* design rule 17 lets the token sit here and in brand/Mark.tsx only).  */
/* Red on white is the lead: white script on red is Coca-Cola's ground, */
/* so `color` is for the rare one-colour use, never a white-on-red      */
/* wordmark at size.                                                    */
/*                                                                      */
/* TWO CUTS, ONE BOX. Under 40pt tall the drip's bead fills in and      */
/* reads as a blot, so below that the drip-less cut (wordmark-sm) is    */
/* drawn instead. It is drawn in the full cut's box, at the same letter */
/* size, so a screen that crosses 40pt with Larger Text moves nothing:  */
/* the drip simply is not there.                                        */
/*                                                                      */
/* LARGER TEXT. The wordmark grows with the text size only so far, as   */
/* the Playfair one did through maxFontSizeMultiplier (specs/v3-cabinet */
/* .md 6.5): its height is `height` x min(fontScale, cap). Six tall     */
/* letters at an accessibility size would run off a phone's edges, and  */
/* the name is read out by VoiceOver anyway. Smaller text sizes shrink  */
/* it, as they shrank the Text.                                         */
/*                                                                      */
/* ONE IMAGE NAMED "Sipply" to VoiceOver (a header where the old Text   */
/* was one), and left alone by Smart Invert, which would turn the red   */
/* to cyan.                                                             */
/* ==================================================================== */

const [VIEW_X, , VIEW_W, VIEW_H] = WORDMARK_PATH.viewBox;
const VIEWBOX = WORDMARK_PATH.viewBox.join(' ');

/** The cap the Playfair wordmark had (maxFontSizeMultiplier 1.2). */
export const WORDMARK_CAP = 1.2;
/** Under this many points tall the drip-less cut is drawn (specs/v4.5-logo/scribble/notes.md). */
export const WORDMARK_SM_BELOW = 40;

/**
 * The large wordmark: sign-in's first step, the onboarding welcome and
 * the password reset, where Playfair 44 stood. 66pt puts the x-height at
 * 23.1, Playfair 44's, so the name keeps its weight on those pages; the
 * box is taller than Playfair's 50pt line because it holds the l's loop
 * and the swash, which a line of type leaves to its neighbours.
 */
export const WORDMARK_LG = 66;

/** Width over height of the wordmark's box. */
export const WORDMARK_ASPECT = VIEW_W / VIEW_H;
/**
 * From the box's left edge to the letters' origin, as a share of its
 * height. The s's tail flicks out past the letters to a point, so a
 * wordmark set left shifts its box out by this much and the s's body
 * lands on the column, not its hairline tail.
 */
export const WORDMARK_LEAD = -VIEW_X / VIEW_H;
/** The x-height as a share of the box's height: 14.7pt at Home's 42, 23.1 at WORDMARK_LG. */
export const WORDMARK_X_HEIGHT = (WORDMARK_BASELINE - WORDMARK_X_TOP) / VIEW_H;

export interface WordmarkProps {
  /** The box's height at the default text size, in points. The drawn height is this x min(fontScale, cap). */
  height: number;
  /** Defaults to the accent: the logo is Campari. */
  color?: string;
  /** How far Larger Text may grow it. */
  cap?: number;
  /** A screen's heading (Home's bar, the welcome): VoiceOver's header trait. */
  header?: boolean;
  /** Off where a parent already hides its head from VoiceOver. */
  accessible?: boolean;
  /**
   * Set left on a column: the box moves out by the s's tail (WORDMARK_LEAD)
   * at the DRAWN height, so the s's body stays on the column at every text
   * size. A caller's own margin would use the unscaled height and drift.
   */
  lead?: boolean;
  style?: StyleProp<ViewStyle>;
}

export function Wordmark({
  height,
  color = colors.accent,
  cap = WORDMARK_CAP,
  header = false,
  accessible = true,
  lead = false,
  style,
}: WordmarkProps) {
  const { fontScale } = useWindowDimensions();
  const h = height * Math.min(fontScale, cap);
  const cut = h < WORDMARK_SM_BELOW ? WORDMARK_SM_PATH : WORDMARK_PATH;
  const w = h * WORDMARK_ASPECT;
  return (
    <View
      accessible={accessible}
      /* No role or name on a wordmark VoiceOver is not meant to reach. */
      accessibilityRole={accessible ? (header ? 'header' : 'image') : undefined}
      accessibilityLabel={accessible ? 'Sipply' : undefined}
      accessibilityIgnoresInvertColors
      pointerEvents="none"
      style={[{ width: w, height: h }, lead && { marginLeft: -WORDMARK_LEAD * h }, style]}>
      <Svg width={w} height={h} viewBox={VIEWBOX}>
        <Path d={cut.d} fill={color} />
      </Svg>
    </View>
  );
}
